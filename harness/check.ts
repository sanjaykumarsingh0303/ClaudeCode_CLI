import { execFile } from "node:child_process";
import { readdir, readFile, access } from "node:fs/promises";
import path from "node:path";

export const HEADER = "// Generated by fake-harness";

export async function exists(file: string): Promise<boolean> {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

export type TestReport = {
  status: "PASS" | "FAIL";
  pass: number;
  fail: number;
  files: number;
  output: string;
};

export async function runTests(workspace: string, filter?: string): Promise<TestReport> {
  const testDir = path.join(workspace, "test");
  if (!(await exists(testDir))) {
    return { status: "FAIL", pass: 0, fail: 0, files: 0, output: "No tests found in workspace/test." };
  }
  const files = (await readdir(testDir))
    .filter((file) => file.endsWith(".test.js"))
    .filter((file) => !filter || file.includes(filter))
    .map((file) => path.join(testDir, file));
  if (files.length === 0) {
    const output = filter
      ? `No test files match "${filter}".`
      : "No tests found in workspace/test.";
    return { status: "FAIL", pass: 0, fail: 0, files: 0, output };
  }
  const output = await new Promise<string>((resolve) => {
    execFile(
      process.execPath,
      ["--test", "--test-reporter=tap", ...files],
      { cwd: workspace, timeout: 60_000, maxBuffer: 5_000_000 },
      (_error, stdout, stderr) => resolve(`${stdout}\n${stderr}`),
    );
  });
  const count = (label: string) =>
    Number(output.match(new RegExp(`^# ${label} (\\d+)`, "m"))?.[1] ?? 0);
  const pass = count("pass");
  const fail = count("fail");
  const status = fail === 0 && pass > 0 ? "PASS" : "FAIL";
  return { status, pass, fail, files: files.length, output };
}

export function formatTests(report: TestReport): string {
  const summary = `${report.status}: ${report.pass} passed, ${report.fail} failed (${report.files} file(s))`;
  if (report.status === "PASS") return summary;
  const tail = report.output.length > 6000 ? "...\n" + report.output.slice(-6000) : report.output;
  return `${summary}\n\n${tail.trim()}`;
}

export type LintIssue = { file: string; line: number; rule: string; message: string };

export async function lintWorkspace(
  workspace: string,
  file?: string,
): Promise<{ issues: LintIssue[]; fileCount: number }> {
  const srcDir = path.join(workspace, "src");
  if (!(await exists(srcDir))) return { issues: [], fileCount: 0 };
  const names = (await readdir(srcDir)).filter(
    (name) => name.endsWith(".js") && (!file || name === path.basename(file)),
  );
  const issues: LintIssue[] = [];
  for (const name of names) {
    const lines = (await readFile(path.join(srcDir, name), "utf8")).split("\n");
    if (!lines[0]?.startsWith(HEADER)) {
      issues.push({ file: name, line: 1, rule: "header", message: "missing harness header" });
    }
    lines.forEach((line, index) => {
      const at = (rule: string, message: string) =>
        issues.push({ file: name, line: index + 1, rule, message });
      if (/console\.log\(/.test(line)) at("no-console", "remove console.log");
      if (/\bvar\s/.test(line)) at("no-var", "use const or let");
      if (/\bTODO\b/.test(line)) at("no-todo", "replace the TODO");
      if (/not implemented/.test(line)) at("no-stub", "stub not implemented yet");
      if (line.length > 100) at("max-len", `line is ${line.length} chars (max 100)`);
    });
  }
  return { issues, fileCount: names.length };
}

export function formatLint(issues: LintIssue[], fileCount: number): string {
  if (issues.length === 0) return `Lint clean: ${fileCount} file(s).`;
  return (
    `${issues.length} issue(s):\n` +
    issues.map((issue) => `- ${issue.file}:${issue.line} [${issue.rule}] ${issue.message}`).join("\n")
  );
}
